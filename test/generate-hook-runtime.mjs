import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

// The CommonJS executable avoids the ESM loader on the synchronous hook path.
// This is generated from the same implementation, not a second hook engine.
export function hookRuntime() {
  let source = fs.readFileSync(new URL('../scripts/mutagate.mjs', import.meta.url), 'utf8');
  // Comment-only lines become empty lines: the package budget (NFR-2) counts both files, and line numbers stay those of mutagate.mjs.
  // ponytail: a line starting with // inside a multi-line template literal would be blanked too; mutagate.mjs has none.
  source = source.replace(/^[ \t]*\/\/.*$/gm, '');
  source = source.replace(/^#!.*\n/, '// Generated by test/generate-hook-runtime.mjs; edit mutagate.mjs instead.\n\"use strict\";\n');
  source = source.replace(/^export \{ glob \} from '\.\/glob.cjs';\n/m, '');
  source = source.replace(/^import (.+) from '([^']+)';$/gm, (_, binding, specifier) => `const ${binding} = require('${specifier}');`);
  source = source.replace(/^export (?=(?:async )?function|const)/gm, '');
  source = source.replaceAll('fileURLToPath(import.meta.url)', '__filename').replaceAll('import.meta.url', '__filename');
  source = source.replace('process.exitCode = await main();', 'main().then(code => { process.exitCode = code; });');
  if (/^import |^export |await main\(\)/m.test(source)) throw Error('Unsupported module syntax in generated hook runtime');
  return source;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(new URL('../scripts/mutagate-hook.cjs', import.meta.url), hookRuntime());
}
